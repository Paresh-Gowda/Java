class Loops {
    public static void main(String args[]) 
    {
        for(int i=1;i<12;i++)
        {
            System.out.println(i);
        }
        int i=0;
        while(i<5)
        {
            System.out.println("\nJava Coding");
            i++;
        }
        do
        {
            System.out.println("\nParesh");
        }
        while(i<2);
    }
}